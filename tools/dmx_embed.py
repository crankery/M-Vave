#!/usr/bin/env python3
"""Generate compact flash-resident sound data for the FM-1 DMX prototype."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOUNDS = (
    ("KICK", ("21KICK",)),
    ("SNARE", ("SNARE6",)),
    ("HAT", ("HAT1A",)),
    ("SMALL_TOM", ("STOM5",)),
    ("LARGE_TOM", ("SFLTOM2",)),
    ("PERC1", ("STIK",)),
    ("PERC2", ("SHAKE6",)),
    ("RIDE", ("RIDE2A1", "RIDE2A2", "RIDE2A3", "RIDE2A4")),
    ("CRASH", ("CRASH1", "CRASH2", "CRASH3", "CRASH4")),
    ("DX_KICK", ("KICK64",)),
    ("DX_SNARE", ("DXSNARE",)),
    ("DX_HAT", ("DXHATS",)),
    ("DX_TOM", ("DXTOM",)),
    ("DX_PERC2", ("DXSHAKE",)),
)
OUTPUT = ROOT / "dinghy" / "firmware" / "src" / "dmx_roms.h"


def main() -> None:
    sounds = []
    for label, names in SOUNDS:
        parts = []
        for name in names:
            path = ROOT / "DMX_Roms" / f"{name}.BIN"
            data = path.read_bytes()
            expected = 8192 if label.startswith("DX_") else 4096
            if len(data) != expected:
                raise SystemExit(f"{path}: expected {expected} bytes, got {len(data)}")
            parts.append(data)
        sounds.append((label, names, b"".join(parts)))
    offsets = []
    position = 0
    for _, _, data in sounds:
        offsets.append(position)
        position += len(data)
    lines = [
        "/* Generated by tools/dmx_embed.py; original ROM bytes, no decoding. */",
        "#ifndef DMX_ROMS_H",
        "#define DMX_ROMS_H",
        "#include <stdint.h>",
        f"#define DMX_ROM_COUNT {len(sounds)}u",
        "#define DMX_ROM_LENGTH 4096u",
        *[f"#define DMX_ROM_{label} {i}u" for i, (label, _, _) in enumerate(sounds)],
        "static const uint32_t dmx_rom_offset[DMX_ROM_COUNT] = {" +
        ", ".join(f"{offset}u" for offset in offsets) + "};",
        "static const uint16_t dmx_rom_length[DMX_ROM_COUNT] = {" +
        ", ".join(f"{len(data)}u" for _, _, data in sounds) + "};",
        f"static const uint8_t dmx_rom_data[{position}u] = {{",
    ]
    for label, names, data in sounds:
        lines.append(f"    /* {label}: {', '.join(name + '.BIN' for name in names)} */")
        for offset in range(0, len(data), 16):
            chunk = data[offset:offset + 16]
            lines.append("        " + ", ".join(f"0x{value:02x}" for value in chunk) + ",")
    lines += ["};", "#endif", ""]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines))
    print(f"{OUTPUT}: {len(sounds)} sounds, {position} bytes")


if __name__ == "__main__":
    main()
