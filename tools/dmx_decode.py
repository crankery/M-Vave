#!/usr/bin/env python3
"""Decode raw DMX sound EPROMs with the Am6070 DAC transfer curve.

Reference: Docs/am6070.pdf, Table 3 (normalized decoder output).
ROM bytes remain 8-bit; the generated C table permits integer-only playback.
"""

import argparse
import struct
import wave
from pathlib import Path


FULL_SCALE = 8031  # Am6070 Table 3, chord 7 / step 15


def decode_byte(code: int) -> int:
    """Return signed 16-bit PCM for one sign/chord/step ROM byte.

    Bit 7 is the sign bit, bits 6..4 the chord, and bits 3..0 the step.
    The positive polarity for sign=1 follows the datasheet's example output
    circuit. A drum machine's analog output stage may invert this polarity.
    """
    chord = (code >> 4) & 7
    step = code & 15
    magnitude = ((2 * step + 33) << chord) - 33
    pcm = (magnitude * 32767 + FULL_SCALE // 2) // FULL_SCALE
    return pcm if code & 0x80 else -pcm


TABLE = tuple(decode_byte(code) for code in range(256))


def write_wav(source: Path, target: Path, sample_rate: int) -> None:
    pcm = [TABLE[code] for code in source.read_bytes()]
    target.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(target), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(sample_rate)
        wav.writeframes(struct.pack(f"<{len(pcm)}h", *pcm))


def write_c_header(target: Path) -> None:
    lines = [
        "/* Generated by tools/dmx_decode.py from the Am6070 Table 3 curve. */",
        "#ifndef DMX_DECODE_TABLE_H",
        "#define DMX_DECODE_TABLE_H",
        "#include <stdint.h>",
        "static const int16_t dmx_decode_table[256] = {",
    ]
    for start in range(0, 256, 8):
        lines.append("    " + ", ".join(f"{value:6d}" for value in TABLE[start:start + 8]) + ",")
    lines += ["};", "#endif", ""]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("roms", nargs="*", type=Path, help="raw sound EPROM files")
    parser.add_argument("--sample-rate", type=int, default=24000,
                        help="WAV playback rate in Hz (default: 24000)")
    parser.add_argument("--out-dir", type=Path, default=Path("build/dmx-preview"))
    parser.add_argument("--c-header", type=Path, help="write an integer-only C lookup table")
    args = parser.parse_args()
    if not args.roms and not args.c_header:
        parser.error("provide ROM files or --c-header")
    if not 1 <= args.sample_rate <= 192000:
        parser.error("sample rate must be between 1 and 192000 Hz")

    if args.c_header:
        write_c_header(args.c_header)
        print(args.c_header)
    for source in args.roms:
        if not source.is_file():
            parser.error(f"ROM file not found: {source}")
        target = args.out_dir / f"{source.stem}.wav"
        write_wav(source, target, args.sample_rate)
        print(target)


if __name__ == "__main__":
    main()
